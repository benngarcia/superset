export function monsterIndex(identity: string): number {
	let hash = 0;
	for (const char of identity.toLowerCase())
		hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
	return hash % (MONSTERS.length + 1);
}

export function monsterFrame(
	identity: string,
	frame: FrameName,
): readonly string[] {
	const index = monsterIndex(identity);
	if (index === 0) return FRAMES[frame];
	const rows = (MONSTERS[index - 1] ?? MONSTERS[0]).map((row) =>
		row.padEnd(SPRITE_SIZE, ".").slice(0, SPRITE_SIZE),
	);
	const bouncing = frame === "run1" || frame === "run3" || frame === "idle";
	const attacking = frame === "bite" || frame === "roar";
	return rows.map((row, y) => {
		if (bouncing && y > 15)
			return frame === "run3" ? `.${row.slice(0, -1)}` : `${row.slice(1)}.`;
		if (attacking && y > 7 && y < 12) return `${row.slice(2)}##`;
		if (frame === "hurt" && y === 6) return row.replaceAll("##", "#.");
		return row;
	});
}
